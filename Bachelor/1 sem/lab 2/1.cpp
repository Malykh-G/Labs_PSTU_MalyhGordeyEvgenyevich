#include <iostream>
#include <iomanip> // Для форматирования вывода (setprecision)
#include <clocale>
using namespace std;
int main() {
    setlocale(LC_ALL, "ru_RU.UTF-8");
    double accuracy = 1e-4; // Заданная точность 10^-4
    double a_n = 0.5;      // Первый член ряда (при n=1): (3^1 * 1!) / 3! = 3/6 = 0.5
    double sum = 0.0;      // Переменная для накопления суммы
    int n = 1;             // Номер текущего члена ряда
    cout << "Вычисление суммы ряда с точностью " << accuracy << endl;
    cout << endl;
    cout << "N\tТекущий член (a_n)\tНакопленная сумма" << endl;
    cout << endl;
    // Цикл работает, пока текущий член ряда больше или равен точности
    while (a_n >= accuracy) {
        sum += a_n; // Добавляем текущий член к сумме
        // Выводим промежуточные результаты
        cout << n << "\t" << a_n << "\t\t" << sum << "\n";
        n++; // Увеличиваем номер члена ряда
        // Вычисляем следующий член по рекуррентной формуле: a_{n+1} = a_n / ((3n+1)*(3n+2))
        // Так как n уже увеличено, то (3n+1) запишется как (3*n - 2), а (3n+2) как (3*n - 1)
        a_n = a_n / ((3.0 * n - 2) * (3.0 * n - 1));
    }
    return 0;
}